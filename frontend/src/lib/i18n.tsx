export type Strings = (typeof strings)["es"];
export type TradeId = keyof Strings["trades"];

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Strings }>({
  lang: "es",
  setLang: () => {},
  t: strings.es,
});

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("es");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("mano.lang");
      if (saved === "es" || saved === "en") setLangState(saved);
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang; // screen readers read the page in the right language
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("mano.lang", l);
    } catch {}
  };

  return (
    <LangContext.Provider value={{ lang, setLang, t: strings[lang] as Strings }}>
      {children}
    </LangContext.Provider>
  );
}

export const useLang = () => useContext(LangContext);
